"""Merge per-stage scenario CSVs into one normalized decision table for a crop.

Usage: uv run python scripts/build_decision_table.py olive
Reads  docs/scenarios/csv/*.csv (or --src), configs/variable_catalog.yaml
Writes configs/crops/<crop>/decision_table.csv and docs/data-requirements.md
"""
import argparse
import csv
import re
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OPS = {"gte": ">=", "gt": ">", "lte": "<=", "lt": "<", "eq": "="}


def classify(variable: str, catalog: list[dict]) -> dict:
    v = variable.lower()
    for d in catalog:
        if any(re.search(p, v) for p in d["match"]):
            return d
    return {"id": "unclassified", "data_class": "unclassified"}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("crop")
    ap.add_argument("--src", default=str(ROOT / "docs/scenarios/csv"))
    a = ap.parse_args()
    catalog = yaml.safe_load((ROOT / "configs/variable_catalog.yaml").read_text())["drivers"]

    rows = []
    for f in sorted(Path(a.src).glob("*.csv")):
        with open(f, newline="") as fh:
            rows += list(csv.DictReader(fh))
    out = []
    for r in rows:
        d = classify(r["variable"], catalog)
        r["operator"] = OPS.get(r["operator"], r["operator"])
        r["driver"] = d["id"]
        r["data_class"] = d["data_class"]
        r["threshold_status"] = "NAV" if "NAV" in (r["threshold"], r["operator"]) else "set"
        out.append(r)

    dest = ROOT / "configs/crops" / a.crop
    dest.mkdir(parents=True, exist_ok=True)
    cols = list(out[0].keys())
    with open(dest / "decision_table.csv", "w", newline="") as f:
        w = csv.DictWriter(f, cols)
        w.writeheader()
        w.writerows(out)

    # data requirements, derived from the table
    need = defaultdict(lambda: {"rows": 0, "ids": []})
    for r in out:
        if r["data_class"] == "climate":
            need[r["driver"]]["rows"] += 1
    lines = [f"# Data requirements — {a.crop} (generated by scripts/build_decision_table.py)\n",
             f"{len(out)} trigger rows; by data class:\n"]
    by_class = defaultdict(int)
    for r in out:
        by_class[r["data_class"]] += 1
    lines += [f"- {k}: {v}" for k, v in sorted(by_class.items())]
    lines += ["\n## Climate drivers → ERA5 request\n", "| driver | rows | dataset | variables |", "|---|---|---|---|"]
    for d in catalog:
        if d["id"] in need:
            e = d["era5"]
            lines.append(f"| {d['id']} | {need[d['id']]['rows']} | {e['dataset']} | {', '.join(e['variables'])} |")
    (ROOT / "docs/data-requirements.md").write_text("\n".join(lines) + "\n")
    print(dict(by_class), "unclassified:", [r["scenario_id"] for r in out if r["driver"] == "unclassified"])


if __name__ == "__main__":
    main()
